-- Additive migration; preserves existing customers, orders, stock, and JSON cart backups.
CREATE TABLE IF NOT EXISTS CUSTOMER_CART_STATE (
 customer_id INT NOT NULL PRIMARY KEY,
 legacy_imported TINYINT(1) NOT NULL DEFAULT 1,
 CONSTRAINT FK_CART_STATE_CUSTOMER FOREIGN KEY(customer_id) REFERENCES KHACH_HANG(ma_khach_hang)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CUSTOMER_CART_ITEM (
 customer_id INT NOT NULL,
 variant_id INT NOT NULL,
 quantity INT NOT NULL,
 PRIMARY KEY(customer_id,variant_id),
 CONSTRAINT CK_CART_QUANTITY CHECK(quantity BETWEEN 1 AND 999),
 CONSTRAINT FK_CART_ITEM_CUSTOMER FOREIGN KEY(customer_id) REFERENCES KHACH_HANG(ma_khach_hang),
 CONSTRAINT FK_CART_ITEM_VARIANT FOREIGN KEY(variant_id) REFERENCES BIEN_THE_SP(ma_bien_the) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS MOBILE_ORDER_REQUEST (
 customer_id INT NOT NULL,
 request_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_id INT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(customer_id,request_key),
 CONSTRAINT FK_ORDER_REQUEST_CUSTOMER FOREIGN KEY(customer_id) REFERENCES KHACH_HANG(ma_khach_hang),
 CONSTRAINT FK_ORDER_REQUEST_ORDER FOREIGN KEY(order_id) REFERENCES DON_HANG(ma_don_hang)
) ENGINE=InnoDB;

